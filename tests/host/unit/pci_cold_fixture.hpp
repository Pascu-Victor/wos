inline void use_captured_profile() {
    hpet.assign(captured_profile::HPET.begin(), captured_profile::HPET.end());
    fadt.assign(captured_profile::FADT.begin(), captured_profile::FADT.end());
    std::copy(captured_profile::HOST.begin(), captured_profile::HOST.end(), functions[0].config.begin());
    std::copy(captured_profile::LPC.begin(), captured_profile::LPC.end(), functions[31].config.begin());
    // Keep the finite hardware fixture's own BAR/PMM addresses. The complete
    // observed conventional capability chain, including reserved holes, is
    // copied exactly; actual PCI validation/issuers still create every owner.
    std::copy(captured_profile::NIC.begin() + 0x40, captured_profile::NIC.end(), nic().config.begin() + 0x40);
    put(nic().config, 0x34, captured_profile::NIC[0x34], 1);
}

[[nodiscard]] inline auto selected_device() -> pci::PCIDevice* {
    for (size_t i = 0; i < pci::pci_device_count(); ++i) {
        auto* device = pci::pci_get_device(i);
        if (device->bus == 0 && device->slot == 4 && device->function == 0 && device->vendor_id == 0x8086 && device->device_id == 0x10d3)
            return device;
    }
    return nullptr;
}
[[nodiscard]] inline auto acpi_table(std::string_view signature) -> ker::mod::acpi::bounded::Result {
    auto const* bytes = signature == "APIC"   ? &madt
                        : signature == "HPET" ? &hpet
                        : signature == "FACP" ? &fadt
                        : signature == "MCFG" ? &mcfg
                                              : nullptr;
    return bytes ? ker::mod::acpi::bounded::Result{.bytes = *bytes, .physical = 0x800000, .error = ker::mod::acpi::bounded::Error::none}
                 : ker::mod::acpi::bounded::Result{};
}
[[nodiscard]] inline auto ecam_pointer(uint64_t physical) -> uint8_t* {
    if (physical < ECAM || physical >= ECAM + 0x10000000) return nullptr;
    uint64_t const OFFSET = physical - ECAM;
    if ((OFFSET >> 20) != 0 || ((OFFSET >> 12) & 7U) != 0) return absent.data() + (OFFSET & 4095U);
    auto& function = functions[(OFFSET >> 15) & 31U];
    return (function.present ? function.config.data() : absent.data()) + (OFFSET & 4095U);
}
[[nodiscard]] inline auto selected() -> Function* {
    assert(config_depth == 1 && (address & 0x80000000U) != 0);
    if ((address & 0x00ff0700U) != 0) return nullptr;
    auto& function = functions[(address >> 11) & 31U];
    return function.present ? &function : nullptr;
}
[[nodiscard]] inline auto inl(uint16_t port) -> uint32_t {
    assert(port == pci::PCI_CONFIG_DATA);
    ++port_reads;
    auto* function = selected();
    if (function == nullptr) return UINT32_MAX;
    size_t const OFFSET = address & 0xfcU;
    if (OFFSET >= 0x10 && OFFSET < 0x28 && function->sizing[(OFFSET - 0x10) / 4]) return function->sizing_masks[(OFFSET - 0x10) / 4];
    return static_cast<uint32_t>(get(function->config, OFFSET, 4));
}
inline void write(uint16_t port, uint32_t value, size_t width) {
    assert(port >= pci::PCI_CONFIG_DATA && port + width <= pci::PCI_CONFIG_DATA + 4);
    ++port_writes;
    auto* function = selected();
    if (function == nullptr) return;
    size_t const OFFSET = (address & 0xfcU) + port - pci::PCI_CONFIG_DATA;
    if (width == 4 && OFFSET >= 0x10 && OFFSET < 0x28) {
        size_t const BAR = (OFFSET - 0x10) / 4;
        if (value == UINT32_MAX) {
            ++bar_probes;
            if ((get(function->config, 4, 2) & 7U) != 0) ++bad_probe_decodes;
            function->sizing[BAR] = true;
            return;
        }
        if (function->sizing[BAR] && function->fail_bar_restore) return;
        function->sizing[BAR] = false;
    }
    if (OFFSET == 4 && width >= 2) {
        uint32_t const PRIOR = static_cast<uint32_t>(get(function->config, 4, 2));
        if ((value & 2U) != 0 && (PRIOR & 2U) == 0) {
            ++mem_enable_writes;
            if (function->fail_mem_enable) value &= ~2U;
        }
        if ((value & 7U) == 0 && function->fail_decode_off) value |= PRIOR & 7U;
        if (width == 4) {
            put(function->config, 6, get(function->config, 6, 2) & ~(value >> 16), 2);
            put(function->config, 4, value, 2);
            return;
        }
    }
    put(function->config, OFFSET, value, width);
}
inline void outl(uint16_t port, uint32_t value) {
    assert(config_depth == 1);
    if (port == pci::PCI_CONFIG_ADDRESS)
        address = value;
    else
        write(port, value, 4);
}
inline void outw(uint16_t port, uint16_t value) { write(port, value, 2); }
inline void outb(uint16_t port, uint8_t value) { write(port, value, 1); }
