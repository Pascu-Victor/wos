inline void put(std::span<uint8_t> bytes, size_t offset, uint64_t value, size_t width) {
    assert(offset <= bytes.size() && width <= bytes.size() - offset && width <= 8);
    for (size_t i = 0; i < width; ++i) bytes[offset + i] = static_cast<uint8_t>(value >> (8U * i));
}
[[nodiscard]] inline auto get(std::span<const uint8_t> bytes, size_t offset, size_t width) -> uint64_t {
    assert(offset <= bytes.size() && width <= bytes.size() - offset && width <= 8);
    uint64_t result = 0;
    for (size_t i = 0; i < width; ++i) result |= uint64_t{bytes[offset + i]} << (8U * i);
    return result;
}
inline void checksum(std::vector<uint8_t>& bytes) {
    bytes[9] = 0;
    uint8_t sum = 0;
    for (auto byte : bytes) sum = static_cast<uint8_t>(sum + byte);
    bytes[9] = static_cast<uint8_t>(0U - sum);
}
[[nodiscard]] inline auto table(std::string_view signature, size_t length, uint8_t revision) -> std::vector<uint8_t> {
    std::vector<uint8_t> result(length);
    std::copy(signature.begin(), signature.end(), result.begin());
    put(result, 4, length, 4);
    result[8] = revision;
    return result;
}
[[nodiscard]] inline auto nic() -> Function& { return functions[4]; }
inline void setup() {
    // Fresh process only: actual PCI/MM globals are intentionally not reset.
    for (auto& function : functions) function = Function{};
    absent.fill(255);
    registers.fill(0);
    address = 0;
    port_reads = port_writes = bar_probes = mem_enable_writes = bad_probe_decodes = 0;
    config_depth = 0;
    for (size_t slot : {size_t{0}, size_t{4}, size_t{31}}) {
        auto& function = functions[slot];
        function.present = true;
        put(function.config, 0, slot == 0 ? 0x29c08086U : slot == 4 ? 0x10d38086U : 0x29188086U, 4);
        put(function.config, 4, 2, 2);
        put(function.config, 8, slot == 0 ? 0x06000000U : slot == 4 ? 0x02000000U : 0x06010000U, 4);
    }
    put(functions[0].config, 0x60, ECAM | 1, 8);
    put(functions[0].config, 0x9d, 2, 1);  // Explicit smm=off profile, no opaque TSEG.
    auto& device = nic();
    put(device.config, 6, 0x10, 2);
    put(device.config, 0x10, BAR0, 4);
    put(device.config, 0x14, BAR1, 4);
    put(device.config, 0x18, 0xc001, 4);
    put(device.config, 0x34, 0x40, 1);
    put(device.config, 0x40, 0x6005, 2);  // MSI -> PM -> PCIe.
    put(device.config, 0x42, 0x180, 2);
    put(device.config, 0x60, 0x7001, 2);
    put(device.config, 0x62, 3, 2);
    put(device.config, 0x70, 0x10, 2);
    put(device.config, 0x72, 2, 2);
    put(device.config, 0x78, 0x0810, 2);
    device.sizing_masks[0] = device.sizing_masks[1] = 0xfffe0000;
    device.sizing_masks[2] = 0xffffffe1;
    madt = table("APIC", 64, 5);
    put(madt, 36, 0xfee00000, 4);
    madt[44] = 1;
    madt[45] = 12;
    put(madt, 48, 0xfec00000, 4);
    madt[56] = 4;
    madt[57] = 6;
    madt[58] = 255;
    madt[61] = 1;
    // Two trailing bytes would be a malformed subtable, so use exact framing.
    madt.resize(62);
    put(madt, 4, madt.size(), 4);
    checksum(madt);
    hpet = table("HPET", 56, 1);
    hpet[41] = 64;
    put(hpet, 44, 0xfed00000, 8);
    checksum(hpet);
    fadt = table("FACP", 276, 6);
    // Absent optional GAS fields are all-zero; reset uses fixed I/O CF9.
    put(fadt, 112, 1U << 10, 4);
    fadt[116] = 1;
    fadt[117] = 8;
    fadt[119] = 1;
    put(fadt, 120, 0xcf9, 8);
    checksum(fadt);
    mcfg = table("MCFG", 60, 1);
    put(mcfg, 44, ECAM, 8);
    mcfg[55] = 255;
    checksum(mcfg);
    iommu_inventory = ker::dev::iommu::Discovery{};
    iommu_inventory.state = ker::dev::iommu::DiscoveryState::absent;
    iommu_inventory.vendor = ker::dev::iommu::FirmwareVendor::none;
    memory_entries = {{{0, 0x10000000, LIMINE_MEMMAP_USABLE},
                       {BAR0, 2 * BAR_BYTES, LIMINE_MEMMAP_RESERVED},
                       {ECAM, 0x10000000, LIMINE_MEMMAP_RESERVED},
                       {0xfec00000, 0x1400000, LIMINE_MEMMAP_RESERVED}}};
    for (size_t i = 0; i < memory_entries.size(); ++i) memory_pointers[i] = &memory_entries[i];
    memory_map = {0, memory_pointers.size(), memory_pointers.data()};
}
