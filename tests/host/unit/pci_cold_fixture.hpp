constexpr size_t BAR_BYTES = 0x20000;
struct Function {
    alignas(4096) std::array<uint8_t, 4096> config{};
    std::array<uint32_t, 6> sizing_masks{};
    std::array<bool, 6> sizing{};
    bool present{};
    bool fail_mem_enable{}, fail_decode_off{}, fail_bar_restore{};
};
